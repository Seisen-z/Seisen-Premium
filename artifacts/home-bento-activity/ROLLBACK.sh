#!/usr/bin/env sh
set -eu
SCRIPT_DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
TARGET=${1:?Usage: ROLLBACK.sh TARGET_FILE}
cp "$SCRIPT_DIR/ORIGINAL_FILE.ts" "$TARGET"
EXPECTED_HASH='C8307DFF61919EC7970185B07D54CE34A0A7B203A6E28CA5D81C4F17EA847D92'
ACTUAL_HASH=$(sha256sum "$TARGET" | awk '{print toupper($1)}')
test "$ACTUAL_HASH" = "$EXPECTED_HASH"
printf 'ROLLBACK_OK %s\n' "$ACTUAL_HASH"